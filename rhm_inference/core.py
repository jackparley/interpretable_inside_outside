def nested_ranges_as_tensor(i, j, min_split):
    # Generate pairs (k1, k2)
    pairs = [
        (k1, k2)
        for k1 in range(i + min_split, j - min_split + 1)
        for k2 in range(k1 + 1, j)
    ]

    # Convert to a tensor
    if pairs:
        return torch.tensor(pairs)  # Shape: [num_pairs, 2]
    else:
        return torch.empty(
            (0, 2), dtype=torch.int32
        )  # Handle case where no pairs exist

def calculate_entropy(probabilities):
    """
    Calculate the entropy of a tensor of normalized probabilities.

    :param probabilities: A torch tensor of normalized probabilities (must sum to 1).
                          Expected dtype=torch.float64.
    :return: The calculated entropy as a scalar (torch.float64).
    """
    # Ensure probabilities is a torch tensor and avoid log(0) with a mask
    mask = probabilities > 0
    entropy = -torch.sum(probabilities[mask] * torch.log(probabilities[mask]))
    return entropy



def extract_binary_rules_as_tensors(grammar, v):
    """
    Extracts binary rules from the grammar and stores them as tensors.

    Parameters:
    - grammar: dict, the grammar generated by `generate_grammar`.
    - V: int, the number of non-terminal symbols.

    Returns:
    - binary_rule_tensors: dict, where keys are layers and values are tensors (V x V x V).
    """
    binary_rule_tensors = {}

    for layer, rules in grammar.items():
        # Initialize a tensor of shape V x V x V with zeros
        T = torch.zeros((v, v, v))

        for lhs, productions in rules.items():
            for rhs, prob, tipus in productions:
                if tipus == "binary":
                    B, C, _ = rhs  # Right-hand side symbols (B, C)
                    # Fill in the tensor for the rule A -> B C
                    T[int(lhs) % v - 1, int(B) % v - 1, int(C) % v - 1] = prob

        binary_rule_tensors[layer] = T

    return binary_rule_tensors


def extract_ternary_rules_as_tensors(grammar, v):
    """
    Extracts ternary rules from the grammar and stores them as tensors.

    Parameters:
    - grammar: dict, the grammar generated by `generate_grammar`.
    - V: int, the number of non-terminal symbols.

    Returns:
    - ternary_rule_tensors: dict, where keys are layers and values are tensors (V x V x V x V).
    """
    ternary_rule_tensors = {}

    for layer, rules in grammar.items():
        # Initialize a tensor of shape V x V x V x V with zeros
        T = torch.zeros((v, v, v, v))

        for lhs, productions in rules.items():
            for rhs, prob, tipus in productions:
                if tipus == "ternary":
                    B, C, D = rhs  # Right-hand side symbols (B, C , D)
                    # Fill in the tensor for the rule A -> B C D
                    T[
                        int(lhs) % v - 1, int(B) % v - 1, int(C) % v - 1, int(D) % v - 1
                    ] = prob

        ternary_rule_tensors[layer] = T

    return ternary_rule_tensors


