def outside_algorithm_2(sequence, grammar, L, v, inside_tensor, root_symbols=None):
    n = len(sequence)

    # Same nonterminal ordering as inside_algorithm_2
    non_terminals = [str(i) for i in range(1, (L + 1) * v + 1)]
    non_terminal_index = {nt: idx for idx, nt in enumerate(non_terminals)}

    # outside_tensor[i, j, A] = outside weight of A spanning sequence[i:j]
    outside_tensor = np.zeros_like(inside_tensor)

    # ------------------------------------------------------------
    # Initialize outside weights at the full span.
    # By default, assume roots are the first layer: 1, ..., v.
    # ------------------------------------------------------------
    if root_symbols is None:
        root_symbols = [str(i) for i in range(1, v + 1)]

    for root in root_symbols:
        outside_tensor[0, n, non_terminal_index[root]] = 1.0/v # Uniformly distribute outside weight among root symbols

    # ------------------------------------------------------------
    # Traverse spans from large to small.
    # Parent outside weights are pushed down to children.
    # ------------------------------------------------------------
    for length in range(n, 1, -1):
        for i in range(n - length + 1):
            j = i + length

            # ----------------------------------------------------
            # Binary rules: lhs -> A B
            # span (i,j) split into (i,k), (k,j)
            # ----------------------------------------------------
            for k in range(i + 1, j):

                for layer_name, rules_at_layer in grammar.items():
                    for lhs, productions in rules_at_layer.items():

                        lhs_idx = non_terminal_index[lhs]
                        parent_outside = outside_tensor[i, j, lhs_idx]

                        if parent_outside == 0:
                            continue

                        for rhs, prob in productions:
                            if len(rhs) != 2:
                                continue

                            A, B = rhs
                            A_idx = non_terminal_index[A]
                            B_idx = non_terminal_index[B]

                            inside_A = inside_tensor[i, k, A_idx]
                            inside_B = inside_tensor[k, j, B_idx]

                            # Contribution to outside of A:
                            # outside(A) += outside(lhs) * prob(lhs -> A B) * inside(B)
                            if inside_B > 0:
                                outside_tensor[i, k, A_idx] += (
                                    parent_outside * prob * inside_B
                                )

                            # Contribution to outside of B:
                            # outside(B) += outside(lhs) * prob(lhs -> A B) * inside(A)
                            if inside_A > 0:
                                outside_tensor[k, j, B_idx] += (
                                    parent_outside * prob * inside_A
                                )

            # ----------------------------------------------------
            # Ternary rules: lhs -> A B C
            # span (i,j) split into (i,k1), (k1,k2), (k2,j)
            # ----------------------------------------------------
            for k1 in range(i + 1, j):
                for k2 in range(k1 + 1, j):

                    for layer_name, rules_at_layer in grammar.items():
                        for lhs, productions in rules_at_layer.items():

                            lhs_idx = non_terminal_index[lhs]
                            parent_outside = outside_tensor[i, j, lhs_idx]

                            if parent_outside == 0:
                                continue

                            for rhs, prob in productions:
                                if len(rhs) != 3:
                                    continue

                                A, B, C = rhs
                                A_idx = non_terminal_index[A]
                                B_idx = non_terminal_index[B]
                                C_idx = non_terminal_index[C]

                                inside_A = inside_tensor[i, k1, A_idx]
                                inside_B = inside_tensor[k1, k2, B_idx]
                                inside_C = inside_tensor[k2, j, C_idx]

                                # Contribution to outside of A
                                if inside_B > 0 and inside_C > 0:
                                    outside_tensor[i, k1, A_idx] += (
                                        parent_outside
                                        * prob
                                        * inside_B
                                        * inside_C
                                    )

                                # Contribution to outside of B
                                if inside_A > 0 and inside_C > 0:
                                    outside_tensor[k1, k2, B_idx] += (
                                        parent_outside
                                        * prob
                                        * inside_A
                                        * inside_C
                                    )

                                # Contribution to outside of C
                                if inside_A > 0 and inside_B > 0:
                                    outside_tensor[k2, j, C_idx] += (
                                        parent_outside
                                        * prob
                                        * inside_A
                                        * inside_B
                                    )

    return outside_tensor



def parallel_inside_masked(
    sequence,
    combined_tensor_bin,
    combined_tensor_ter,
    L,
    v,
    mask_from=None,
    padded=None,
    observed_positions=None,
):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    d = len(sequence)
    # n is the effective length for tensor sizing:
    # padded (e.g. 3**L) removes prior knowledge of sentence length;
    # None (default) keeps the original behaviour where n == d.
    n = padded if padded is not None else d
    ls = range(1, L + 1)
    tensor_list=[]
    # Collect all non-terminals from all layers
    non_terminals = [str(i) for i in range(1, (L + 1) * v + 1)]

    # num_non_terminals = len(non_terminals)

    # Create a tensor for inside weights: (n+1) x (n+1) x (num_non_terminals)
    inside_tensor = torch.zeros((v, n + 1, n + 1), dtype=torch.float64).to(device)
    
    # Mapping from non-terminal to its index in the tensor
    non_terminal_index = {nt: idx for idx, nt in enumerate(non_terminals)}

    # ``observed_positions`` allows non-contiguous evidence (for example, only
    # the two tokens immediately before the masked last token).  Positions are
    # zero-based.  If it is omitted, retain the original suffix-masking API.
    if observed_positions is None:
        if mask_from is None:
            mask_from = d
    else:
        observed_positions = set(observed_positions)

    # Base case: fill for length 1
    # Positions beyond the actual sentence (i > d) are padding: treat as uniform.
    for i in range(1, n + 1):
        is_observed = (
            i <= d
            and (
                (observed_positions is None and i < mask_from)
                or (observed_positions is not None and i - 1 in observed_positions)
            )
        )
        if not is_observed:
            inside_tensor[:, i - 1, i] = 1.0 / v
        else:
            leaf = sequence[i - 1]
            # Grammar symbols are globally numbered by layer.  Modulo v maps
            # a terminal to its vocabulary class even when inference is run at
            # a depth smaller than the grammar that generated the sequence.
            leaf_class = (int(leaf) - 1) % v
            inside_tensor[leaf_class][i - 1][i] = 1
    tensor_list.append(inside_tensor)

    # Fill the tensor for lengths greater than 1
    for ll in ls:
        inside_tensor_new = torch.zeros((v, n + 1, n + 1), dtype=torch.float64).to(
            device
        )
        ll_2 = L - ll

        min_d = 2**ll
        max_d = min(3**ll, n)

        # Binary rules
        rule_tensor_bin = combined_tensor_bin[ll_2].to(device)  # Shape: [V,V,V]
        # Ternary rules
        rule_tensor_ter = combined_tensor_ter[ll_2].to(device)  # Shape:
        min_split = int(2 ** (ll - 1))

        for length in range(min_d, max_d + 1):  # Length of the span
            kk_0 = np.array(range(min_split, length - min_split + 1))
            kk_0 = torch.tensor(kk_0).to(device)
            pairs_0 = nested_ranges_as_tensor(0, length, min_split)
            pairs_0 = pairs_0.to(device)
            for i in range(n - length + 1):  # Start position
                j = i + length  # End position

                # First go over the binary rules

                span_probabilities = torch.zeros(v, dtype=torch.float64).to(device)

                # Vector of split positions
                kk = kk_0 + i
                left = (
                    inside_tensor[:, i, kk].permute(1, 0).unsqueeze(2)
                )  # Shape: [K, V, 1]
                right = (
                    inside_tensor[:, kk, j].permute(1, 0).unsqueeze(1)
                )  # Shape: [K, 1, V]

                # Compute contributions via broadcasting
                inter = left * right  # [K,V,V]
                inter_2 = inter.unsqueeze(1)  # [K,1,V,V]
                contributions = rule_tensor_bin * inter_2  # Shape: [K, V, V, V]
                span_probabilities += contributions.sum(
                    dim=(0, 2, 3)
                )  # Sum over k, B and C
                inside_tensor_new[:, i, j] += span_probabilities

                # Go over ternary rules

                span_probabilities = torch.zeros(v, dtype=torch.float64).to(device)

                pairs = pairs_0 + i  # List of pairs of splits
                pairs = pairs.to(device)
                left = (
                    inside_tensor[:, i, pairs[:, 0]]
                    .permute(1, 0)
                    .unsqueeze(2)
                    .unsqueeze(3)
                )  # Shape: [Np, V, 1, 1]
                middle = (
                    inside_tensor[:, pairs[:, 0], pairs[:, 1]]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(3)
                )  # Shape: [Np, 1,V,1]
                right = (
                    inside_tensor[:, pairs[:, 1], j]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(2)
                )  # Shape: [Np, 1, 1, V]

                # Compute contributions via broadcasting
                inter = left * middle * right
                inter_2 = inter.unsqueeze(1)  # Shape [Np, 1, V, V, V]
                contributions = rule_tensor_ter * inter_2  # Shape: [V, V, V, V]
                span_probabilities += contributions.sum(
                    dim=(0, 2, 3, 4)
                )  # Sum over Np, B, C and D
                inside_tensor_new[:, i, j] += span_probabilities
        
        inside_tensor = inside_tensor_new
        tensor_list.append(inside_tensor_new)
    return inside_tensor, tensor_list



def parallel_outside(
    d,
    combined_tensor_bin,
    combined_tensor_ter,
    L,
    v,
    inside_tensor_list,
    padded=None,
    uniform_root_span_lengths=None,
):

    
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    # n is the effective length matching the inside tensor produced by parallel_inside_masked.
    # padded removes prior knowledge of sentence length; None keeps the original behaviour.
    n = padded if padded is not None else d
    outside_tensor = torch.zeros((v, n + 1, n + 1), dtype=torch.float64).to(device)
    if uniform_root_span_lengths is not None:
        # Depth-restricted inference has no known parent above this level.
        # Put the boundary condition directly on every admissible span at the
        # highest known level, uniformly over its latent symbol.  A common
        # multiplicative constant over spans cancels when the final-token
        # marginal is normalized.
        for length in uniform_root_span_lengths:
            if length > n:
                continue
            starts = torch.arange(n - length + 1, device=device)
            outside_tensor[:, starts, starts + length] = 1.0 / v
    elif padded is not None:
        # Uniform prior over all possible sentence lengths: every span (0, k) gets 1/v.
        outside_tensor[:, 0, :] = 1.0 / v
    else:
        outside_tensor[:, 0, -1] = 1/v*torch.ones((v,), dtype=torch.float64).to(device)
    outside_tensor_list=[outside_tensor]
    ll=L
    ll_2=0
    jjj=-2
    for kkk in range(L):
        outside_tensor_new = torch.zeros((v, n + 1, n + 1), dtype=torch.float64).to(
                    device
                )
        min_d = 2**(ll)
        #max_d = min(3**(ll), d)
        max_d=n

        # Binary rules
        rule_tensor_bin = combined_tensor_bin[ll_2].to(device)  # Shape: [V,V,V]
        # Ternary rules
        rule_tensor_ter = combined_tensor_ter[ll_2].to(device)  # Shape:
        min_split = int(2 ** (ll - 1))
        #min_split=2
        inside_tensor=inside_tensor_list[jjj].to(device)

        for length in range(min_d, max_d + 1):  # Length of the span
            kk_0 = np.array(range(min_split, length - min_split + 1))
            kk_0 = torch.tensor(kk_0).to(device)
            Nk=len(kk_0)
            pairs_0 = nested_ranges_as_tensor(0, length, min_split)
            pairs_0 = pairs_0.to(device)
            Np=len(pairs_0)
            for i in range(n - length + 1):  # Start position
                j = i + length  # End position
                
                # First go over the binary rules

                span_probabilities = torch.zeros(Nk,v, dtype=torch.float64).to(device)

                # Vector of split positions
                kk = kk_0 + i
                left=outside_tensor[:, i, j].unsqueeze(-1).unsqueeze(-1).unsqueeze(0) #1,v,1,1
                right=inside_tensor[:, kk, j].permute(1, 0).unsqueeze(1).unsqueeze(2) #NK,1,1,v
                inter = left * right  # Shape: [NK,v,1,v]
                contributions = rule_tensor_bin * inter #Shape:[Nk,v,v,v]
                span_probabilities += contributions.sum(
                            dim=(1, 3)
                        )  # Sum over A and C
                outside_tensor_new[:, i, kk] += span_probabilities.permute(1, 0)

                span_probabilities = torch.zeros(Nk,v, dtype=torch.float64).to(device)

                # Vector of split positions
                kk = kk_0 + i
                left=inside_tensor[:, i, kk].permute(1,0).unsqueeze(1).unsqueeze(-1)
                right=outside_tensor[:, i, j].unsqueeze(-1).unsqueeze(-1).unsqueeze(0)
                inter = left * right  # Shape: [NK,v,v,1]
                contributions = rule_tensor_bin * inter #Shape:[Nk,v,v,v]
                span_probabilities += contributions.sum(
                            dim=(1, 2)
                        )  # Sum over A and B
                outside_tensor_new[:, kk, j] += span_probabilities.permute(1, 0)

                span_probabilities = torch.zeros(Np,v, dtype=torch.float64).to(device)

                pairs = pairs_0 + i  # List of pairs of splits
                pairs = pairs.to(device)
                left = (
                    outside_tensor[:, i, j]
                    .unsqueeze(0)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                )  # Shape: [1, V, 1, 1, 1]
                middle = (
                    inside_tensor[:, pairs[:, 0], pairs[:, 1]]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(2)
                    .unsqueeze(-1)
                )  # Shape: [Np, 1, 1, V, 1]
                right = (
                    inside_tensor[:, pairs[:, 1], j]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(2)
                    .unsqueeze(3)
                )  # Shape: [Np, 1, 1, 1, V]
                # Compute contributions via broadcasting
                inter = left * middle * right
                contributions = (rule_tensor_ter.unsqueeze(0)) * inter  # Shape: [Np,V, V, V, V]
                span_probabilities += contributions.sum(
                    dim=(1, 3, 4)
                )  # Sum over Np, B, C and D
                #outside_tensor_new[:, i, pairs[:, 0]] += span_probabilities.permute(1, 0)
                outside_tensor_new[:, i, :].index_add_(
                    1,
                    pairs[:, 0],
                    span_probabilities.permute(1, 0)
                )
                

                span_probabilities = torch.zeros(Np,v, dtype=torch.float64).to(device)

                pairs = pairs_0 + i  # List of pairs of splits
                pairs = pairs.to(device)
                left = (
                    outside_tensor[:, i, j]
                    .unsqueeze(0)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                )  # Shape: [1, V, 1, 1, 1]
                middle = (
                    inside_tensor[:, i, pairs[:, 0]]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                )  # Shape: [Np, 1, V, 1, 1]
                right = (
                    inside_tensor[:, pairs[:, 1], j]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(2)
                    .unsqueeze(3)
                )  # Shape: [Np, 1, 1, 1, V]
                # Compute contributions via broadcasting
                inter = left * middle * right
                contributions = (rule_tensor_ter.unsqueeze(0)) * inter  # Shape: [Np,V, V, V, V]
                span_probabilities += contributions.sum(
                    dim=(1, 2, 4)
                )  # Sum over A, B and D
                outside_tensor_new[:, pairs[:, 0], pairs[:, 1]] += span_probabilities.permute(1, 0)



                span_probabilities = torch.zeros(Np,v, dtype=torch.float64).to(device)

                pairs = pairs_0 + i  # List of pairs of splits
                pairs = pairs.to(device)
                left = (
                    outside_tensor[:, i, j]
                    .unsqueeze(0)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                )  # Shape: [1, V, 1, 1, 1]
                middle = (
                    inside_tensor[:, i, pairs[:, 0]]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(-1)
                    .unsqueeze(-1)
                )  # Shape: [Np, 1, V, 1, 1]
                right = (
                    inside_tensor[:, pairs[:, 0], pairs[:, 1]]
                    .permute(1, 0)
                    .unsqueeze(1)
                    .unsqueeze(2)
                    .unsqueeze(-1)
                )  # Shape: [Np, 1, 1, V, 1]
                # Compute contributions via broadcasting
                inter = left * middle * right
                contributions = (rule_tensor_ter.unsqueeze(0)) * inter  # Shape: [Np,V, V, V, V]
                span_probabilities += contributions.sum(
                    dim=(1, 2, 3)
                )  # Sum over A, B and C
                #outside_tensor_new[:, pairs[:, 1], j] += span_probabilities.permute(1, 0)
                outside_tensor_new[:, :, j].index_add_(
                    1,  # add along dim=1
                    pairs[:, 1],
                    span_probabilities.permute(1, 0)
                )


        outside_tensor_list.append(outside_tensor_new)
        outside_tensor = outside_tensor_new.clone()
        ll=ll-1
        ll_2=ll_2+1
        jjj=jjj-1

    return outside_tensor,outside_tensor_list
