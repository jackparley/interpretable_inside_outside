def sample_from_grammar(grammar, start_symbol, L, p_2, p_3):
    # Initialize the current symbols with the start symbol
    current_symbols = [start_symbol]
    prob_tree = 1
    # Sequentially apply rules for each layer
    for layer in range(1, L + 1):  # 1 to 3 (3 layers)
        new_symbols = []
        for symbol in current_symbols:
            # Check if the symbol has productions in the current layer
            layer_key = f"layer{layer}"
            if layer_key in grammar and symbol in grammar[layer_key]:
                productions = grammar[layer_key][symbol]
                # Choose a production based on its probability
                total_prob = sum(prob for _, prob in productions)
                rand = random.uniform(0, total_prob)
                cumulative_prob = 0

                for production, prob in productions:
                    cumulative_prob += prob
                    if rand < cumulative_prob:
                        new_symbols.extend(production)  # Expand the symbols
                        # print(len(production))
                        if len(production) == 2:
                            prob_tree = prob_tree * p_2
                        elif len(production) == 3:
                            prob_tree = prob_tree * p_3
                        break
        if new_symbols != []:
            current_symbols = new_symbols
    return current_symbols, prob_tree


def inside_algorithm_2(sequence, grammar, L, v):
    n = len(sequence)

    # Collect all non-terminals from all layers
    non_terminals = [str(i) for i in range(1, (L + 1) * v + 1)]
    # print(non_terminals)
    num_non_terminals = len(non_terminals)

    # Create a tensor for inside weights: (n+1) x (n+1) x (num_non_terminals)
    inside_tensor = np.zeros((n + 1, n + 1, num_non_terminals))

    # Mapping from non-terminal to its index in the tensor
    non_terminal_index = {nt: idx for idx, nt in enumerate(non_terminals)}
    # print(non_terminal_index)

    # Base case: fill for length 1
    for i in range(1, n + 1):
        # parse_table[i - 1][i].add(sequence[i-1])
        leaf = sequence[i - 1]
        inside_tensor[i - 1][i][non_terminal_index[leaf]] = 1

    # Fill the tensor for lengths greater than 1
    for length in range(2, n + 1):  # Length of the span
        for i in range(n - length + 1):  # Start position
            j = i + length  # End position
            # Handle binary productions
            for k in range(i + 1, j):  # Split position for binary
                # for layer in grammar.keys():
                for A in non_terminals:
                    for B in non_terminals:
                        if (
                            inside_tensor[i][k][non_terminal_index[A]] > 0
                            and inside_tensor[k][j][non_terminal_index[B]] > 0
                        ):
                            ll = int(np.floor(non_terminal_index[A] / v))
                            # print(A)

                            layer = f"layer{ll}"
                            # print(layer)
                            for lhs, productions in grammar[layer].items():
                                for rhs, prob in productions:
                                    if rhs == [A, B]:
                                        inside_tensor[i][j][
                                            non_terminal_index[lhs]
                                        ] += (
                                            inside_tensor[i][k][non_terminal_index[A]]
                                            * inside_tensor[k][j][non_terminal_index[B]]
                                            * prob
                                        )

            # Handle ternary productions
            for k1 in range(i + 1, j):  # First split
                for k2 in range(k1 + 1, j):  # Second split
                    # for layer in grammar.keys():
                    for A in non_terminals:
                        for B in non_terminals:
                            for C in non_terminals:
                                if (
                                    inside_tensor[i][k1][non_terminal_index[A]] > 0
                                    and inside_tensor[k1][k2][non_terminal_index[B]] > 0
                                    and inside_tensor[k2][j][non_terminal_index[C]] > 0
                                ):
                                    ll = int(np.floor(non_terminal_index[A] / v))
                                    # print(A)

                                    layer = f"layer{ll}"
                                    for lhs, productions in grammar[layer].items():
                                        for rhs, prob in productions:
                                            if rhs == [A, B, C]:
                                                inside_tensor[i][j][
                                                    non_terminal_index[lhs]
                                                ] += (
                                                    inside_tensor[i][k1][
                                                        non_terminal_index[A]
                                                    ]
                                                    * inside_tensor[k1][k2][
                                                        non_terminal_index[B]
                                                    ]
                                                    * inside_tensor[k2][j][
                                                        non_terminal_index[C]
                                                    ]
                                                    * prob
                                                )

    return inside_tensor


